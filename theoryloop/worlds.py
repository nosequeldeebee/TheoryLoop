"""Planted-mechanism worlds.

Each world is a synthetic panel of NFT projects whose outcome (a 12-month
legitimacy score: holder retention, standardized) is generated by a mechanism
we choose. Because we wrote the mechanism, we know the "true theory" and can
score whatever a theory-building loop produces against it.

Variables are named after constructs from platform-legitimacy research so the
benchmark reads like the substantive setting it stands in for, but nothing in
the loop gets to see the generating code -- only the data.

Design principles
- Every world contains distractor variables (pure noise) so there are many
  forking paths for an analyst to wander down.
- Worlds are chosen to stress specific failure modes:
    main      -- a single true effect (can the loop find a simple truth?)
    scope     -- an effect that exists only under a boundary condition
    confound  -- a decoy correlation produced by a common cause
    null      -- nothing to find (does the loop invent theory anyway?)
    multi     -- a threshold effect plus a second independent effect
"""
from __future__ import annotations

from dataclasses import dataclass, field
import numpy as np
import pandas as pd

from .theory import Proposition

PREDICTORS = [
    "verified",        # marketplace verification badge (binary)
    "creator_rep",     # creator's prior reputation (continuous)
    "community",       # size of Discord/community at launch (continuous)
    "royalty",         # creator royalty rate (0-0.10)
    "wash_share",      # share of early volume that is wash trading (0-1)
    "bear_launch",     # launched in a bear market (binary)
    "roadmap_len",     # length of published roadmap (distractor)
    "art_entropy",     # visual complexity of the collection (distractor)
    "mint_hour",       # hour of day of mint (distractor)
    "supply_log",      # log collection size (distractor)
]
BINARY = {"verified", "bear_launch"}
OUTCOME = "legitimacy"


@dataclass
class World:
    """`truth` is a list of slots. Each slot is the set of propositions that
    are observationally equivalent statements of one planted mechanism. For a
    pure interaction, "X matters when Z=1" and "Z matters when X=1" fit the
    data equally well: which variable is focal is a framing choice the data
    cannot make, so either counts as recovering the mechanism."""
    name: str
    description: str
    truth: list[frozenset]
    data: pd.DataFrame = field(repr=False)


def _base(rng: np.random.Generator, n: int) -> pd.DataFrame:
    return pd.DataFrame({
        "verified": rng.binomial(1, 0.4, n),
        "creator_rep": rng.normal(0, 1, n),
        "community": rng.normal(0, 1, n),
        "royalty": rng.uniform(0, 0.10, n),
        "wash_share": rng.beta(2, 8, n),
        "bear_launch": rng.binomial(1, 0.5, n),
        "roadmap_len": rng.normal(0, 1, n),
        "art_entropy": rng.normal(0, 1, n),
        "mint_hour": rng.integers(0, 24, n).astype(float),
        "supply_log": rng.normal(8, 1, n),
    })


def make_world(name: str, seed: int, n: int = 2000) -> World:
    rng = np.random.default_rng(seed)
    d = _base(rng, n)
    e = rng.normal(0, 1, n)

    if name == "main":
        y = 0.30 * d.verified + e
        truth = [frozenset({Proposition("verified", +1)})]
        desc = "Verification raises legitimacy everywhere."
    elif name == "scope":
        y = 0.45 * d.verified * d.bear_launch + e
        truth = [frozenset({Proposition("verified", +1, ("bear_launch", 1)),
                           Proposition("bear_launch", +1, ("verified", 1))})]
        desc = "Verification matters only for projects launched in a bear market."
    elif name == "confound":
        # community size drives BOTH verification and legitimacy;
        # verification itself does nothing.
        p = 1 / (1 + np.exp(-(1.6 * d.community - 0.4)))
        d["verified"] = rng.binomial(1, p)
        y = 0.40 * d.community + e
        truth = [frozenset({Proposition("community", +1)})]
        desc = "Community drives both verification and legitimacy; verification is a decoy."
    elif name == "null":
        y = e
        truth = []
        desc = "No mechanism. Any proposition is a false discovery."
    elif name == "multi":
        y = -0.55 * (d.wash_share > 0.30) + 0.20 * d.creator_rep + e
        truth = [frozenset({Proposition("wash_share", -1)}), frozenset({Proposition("creator_rep", +1)})]
        desc = "Heavy wash trading destroys legitimacy (threshold); creator reputation helps."
    else:
        raise ValueError(f"unknown world {name}")

    d[OUTCOME] = y
    return World(name, desc, truth, d)


WORLD_NAMES = ["main", "scope", "confound", "null", "multi"]
